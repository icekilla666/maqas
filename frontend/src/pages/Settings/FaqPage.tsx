const FaqPage = () => {
  const [activeIndex, setActiveIndex] = useState<number | null>(null);

  const toggleAccordion = (index: number) => {
    setActiveIndex((prev) => (prev === index ? null : index));
  };

  return (
    <section className="wrapper settings-page">
      <div className="container">
        <TitlePage backTo={SETTINGS_PAGE} backLabel="Вернуться в настройки" title="Часто задаваемые вопросы" />
        <div className="faq-list">
          {faqItems.map((item, index) => {
            const isActive = activeIndex === index;

            return (
              <div
                className={`faq-accordion ${isActive ? "active" : ""}`.trim()}
                key={item.question}
              >
                <button
                  aria-expanded={isActive}
                  className="faq-accordion__trigger"
                  onClick={() => toggleAccordion(index)}
                  type="button"
                >
                  <span>{item.question}</span>
                  <ChevronDown className="faq-accordion__icon" size={26} />
                </button>
                {isActive && (
                  <div className="faq-accordion__content">
                    <p>{item.answer}</p>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </section>
  );
};

export default FaqPage;
